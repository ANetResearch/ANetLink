// Package fingerprint identifies what a device on the local network is,
// before anyone has typed a credential.
//
// ANetLink's premise is a pre-authorised LAN: the operator owns the network
// and wants the daemon to find, name and drive whatever is on it. Naming is
// the step that was missing. WS-Discovery returns an address; a Modbus unit
// returns registers; an unadopted Zigbee coordinator returns nothing at all.
// None of that tells an operator — or an agent — that 192.0.2.71 is a
// Hikvision PTZ dome rather than a printer.
//
// # On nmap
//
// nmap solves the adjacent problem and solves it superbly, and its data
// layout informed this package's shape. Its data files are NOT used, read,
// or shipped here, and must not be. The Nmap Public Source License §3
// defines a derivative work to include anything that "reads or includes
// Covered Software data files, such as nmap-os-db or nmap-service-probes" —
// so reading nmap-mac-prefixes at runtime would place ANetLink under NPSL,
// which conflicts with the ANet Open Source License it ships under.
//
// The OUI data here therefore comes straight from its actual origin, the
// IEEE MA-L registry (which is also where nmap's own file says its data
// comes from), fetched and regenerated by ./gen. Service-level fingerprints
// are written by hand for the protocols ANetLink actually speaks, which is
// both licence-clean and more accurate for this purpose than a general
// scanner's corpus.
package fingerprint

import (
	"encoding/hex"
	"strings"
)

// Class is what kind of thing a device is, coarsely. It answers the question
// an operator actually asks first: "what is that?"
type Class string

const (
	ClassCamera     Class = "camera"     // IP cameras, NVRs, doorbells
	ClassSmartHome  Class = "smart-home" // lights, plugs, sensors, hubs
	ClassLighting   Class = "lighting"   // commercial and architectural lighting
	ClassIndustrial Class = "industrial" // PLCs, gateways, building automation
	ClassNetwork    Class = "network"    // routers, switches, APs
	ClassAppliance  Class = "appliance"  // white goods, HVAC
	ClassRobot      Class = "robot"      // vacuums, quadrupeds, arms
	ClassUnknown    Class = "unknown"
)

// Ecosystem names the vendor's own cloud or protocol family, which is what
// decides how ANetLink reaches the device. A Lumi sensor is Zigbee under an
// Aqara account; a Yeelight bulb is MIoT. Knowing the vendor without knowing
// this leaves an operator no closer to controlling it.
type Ecosystem string

const (
	EcoONVIF   Ecosystem = "onvif"
	EcoISAPI   Ecosystem = "isapi"
	EcoDahua   Ecosystem = "dahua-cgi"
	EcoMIoT    Ecosystem = "miot"
	EcoTuya    Ecosystem = "tuya"
	EcoAqara   Ecosystem = "aqara"
	EcoZigbee  Ecosystem = "zigbee"
	EcoMatter  Ecosystem = "matter"
	EcoModbus  Ecosystem = "modbus"
	EcoBACnet  Ecosystem = "bacnet"
	EcoHomeKit Ecosystem = "homekit"
	EcoNone    Ecosystem = ""
)

// Vendor is one identified manufacturer.
type Vendor struct {
	// Name is the canonical name, not the IEEE registration string. IEEE
	// carries "Hangzhou Hikvision Digital Technology Co.,Ltd." and eighty
	// other spellings of the same company; an operator wants "Hikvision".
	Name string
	// Class is what this vendor's devices usually are. Coarse by design: a
	// vendor making both cameras and doorbells is still ClassCamera.
	Class Class
	// Ecosystems lists how ANetLink can reach these devices, most direct
	// first. Empty means no adapter covers this vendor yet — which is
	// itself worth reporting, since it names a real gap.
	Ecosystems []Ecosystem
	// Adapters names the ANetLink adapters that can drive it, if any.
	Adapters []string
}

// Identification is what fingerprinting concluded about one host.
type Identification struct {
	MAC    string
	Vendor Vendor
	// Found reports whether the OUI resolved at all. A false here is not a
	// failure — unregistered and randomised MACs are ordinary — but it does
	// mean Vendor is a zero value and must not be presented as fact.
	Found bool
}

// normaliseMAC extracts the 24-bit OUI from any of the spellings a MAC
// arrives in: colons, hyphens, dots, bare hex, upper or lower case.
func normaliseMAC(mac string) (uint32, bool) {
	var b strings.Builder
	for _, r := range mac {
		switch {
		case r >= '0' && r <= '9', r >= 'a' && r <= 'f', r >= 'A' && r <= 'F':
			b.WriteRune(r)
		case r == ':' || r == '-' || r == '.' || r == ' ':
			// separators are noise
		default:
			return 0, false
		}
	}
	h := b.String()
	if len(h) < 6 {
		return 0, false
	}
	raw, err := hex.DecodeString(strings.ToUpper(h[:6]))
	if err != nil || len(raw) != 3 {
		return 0, false
	}
	return uint32(raw[0])<<16 | uint32(raw[1])<<8 | uint32(raw[2]), true
}

// VendorByMAC identifies the manufacturer of a MAC address.
//
// A locally-administered address (the second-least-significant bit of the
// first octet) is reported as not found rather than looked up: those are
// randomised or virtual, and resolving one to whichever vendor happens to
// own the range would be a confident wrong answer.
func VendorByMAC(mac string) (Identification, bool) {
	oui, ok := normaliseMAC(mac)
	if !ok {
		return Identification{MAC: mac}, false
	}
	if oui>>16&0x02 != 0 {
		return Identification{MAC: mac}, false // locally administered
	}
	v, found := ouiVendor(oui)
	return Identification{MAC: mac, Vendor: v, Found: found}, found
}

// ouiVendor resolves a 24-bit OUI through the generated table.
func ouiVendor(oui uint32) (Vendor, bool) {
	idx, ok := ouiIndex[oui]
	if !ok || int(idx) >= len(vendors) {
		return Vendor{}, false
	}
	return vendors[idx], true
}

// Vendors returns every vendor in the catalogue, for operators and docs that
// want to know what is covered without reading the generated table.
func Vendors() []Vendor {
	out := make([]Vendor, len(vendors))
	copy(out, vendors)
	return out
}

// CoverageGap reports vendors the catalogue knows by name but no adapter can
// reach. This is the honest inverse of a feature list: it names, concretely,
// which hardware an operator will find on their network and not be able to
// drive.
func CoverageGap() []Vendor {
	var out []Vendor
	for _, v := range vendors {
		if len(v.Adapters) == 0 {
			out = append(out, v)
		}
	}
	return out
}
